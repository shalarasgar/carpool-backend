// Locations serves GET /v1/locations. It is public and cacheable with an ETag.
func (h Me) Locations(w http.ResponseWriter, r *http.Request) {
	list, err := h.Profiles.Locations(r.Context())
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	body, err := json.Marshal(listResponse[locationDTO]{Items: mapList(list, toLocation)})
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	sum := sha256.Sum256(body)
	etag := `"` + hex.EncodeToString(sum[:8]) + `"`
	w.Header().Set("ETag", etag)
	w.Header().Set("Cache-Control", "public, max-age=300")
	if r.Header.Get("If-None-Match") == etag {
		w.WriteHeader(http.StatusNotModified)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	_, _ = w.Write(body)
}

func decodeBody(w http.ResponseWriter, r *http.Request, dst any) bool {
	r.Body = http.MaxBytesReader(w, r.Body, 1<<16)
	dec := json.NewDecoder(r.Body)
	if err := dec.Decode(dst); err != nil {
		badJSON(w, r)
		return false
	}
	return true
}

func readUpload(w http.ResponseWriter, r *http.Request, logger *slog.Logger) ([]byte, bool) {
	r.Body = http.MaxBytesReader(w, r.Body, media.MaxBytes+(64<<10))
	file, _, err := r.FormFile("photo")
	if err != nil {
		var tooLarge *http.MaxBytesError
		if errors.As(err, &tooLarge) {
			writeRideErr(w, r, logger, media.ErrTooLarge)
		} else {
			badJSON(w, r)
		}
		return nil, false
	}
	defer file.Close()
	data, err := io.ReadAll(io.LimitReader(file, media.MaxBytes+1))
	if err != nil {
		badJSON(w, r)
		return nil, false
	}
	return data, true
}
