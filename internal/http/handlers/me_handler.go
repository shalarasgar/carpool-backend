// Me serves the caller's profile, phone change, vehicles, public profiles, and locations.
type Me struct {
	Logger   *slog.Logger
	Profiles *service.Profiles
	DevMode  bool
}

type patchMeRequest struct {
	FirstName *string `json:"first_name"`
	LastName  *string `json:"last_name"`
	Bio       *string `json:"bio"`
	Locale    *string `json:"locale"`
}

// Get returns GET /v1/me.
func (h Me) Get(w http.ResponseWriter, r *http.Request) {
	p, err := h.Profiles.Me(r.Context(), middleware.UserFrom(r.Context()))
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	httperr.WriteJSON(w, http.StatusOK, toProfile(p, true))
}

// Patch serves PATCH /v1/me.
func (h Me) Patch(w http.ResponseWriter, r *http.Request) {
	var body patchMeRequest
	if !decodeBody(w, r, &body) {
		return
	}
	p, err := h.Profiles.Update(r.Context(), middleware.UserFrom(r.Context()), ride.ProfilePatch(body))
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	httperr.WriteJSON(w, http.StatusOK, toProfile(p, true))
}

// UploadPhoto serves POST /v1/me/photo (multipart field "photo").
func (h Me) UploadPhoto(w http.ResponseWriter, r *http.Request) {
	data, ok := readUpload(w, r, h.Logger)
	if !ok {
		return
	}
	p, err := h.Profiles.SetPhoto(r.Context(), middleware.UserFrom(r.Context()), data)
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	httperr.WriteJSON(w, http.StatusOK, toProfile(p, true))
}

// DeletePhoto serves DELETE /v1/me/photo.
func (h Me) DeletePhoto(w http.ResponseWriter, r *http.Request) {
	p, err := h.Profiles.RemovePhoto(r.Context(), middleware.UserFrom(r.Context()))
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	httperr.WriteJSON(w, http.StatusOK, toProfile(p, true))
}

// Delete serves DELETE /v1/me: the caller's account and personal data are erased. It
// answers 409 TRIP_IN_PROGRESS while a trip the caller drives is under way.
func (h Me) Delete(w http.ResponseWriter, r *http.Request) {
	if err := h.Profiles.DeleteAccount(r.Context(), middleware.UserFrom(r.Context())); err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

type phoneChangeRequest struct {
	Phone    string `json:"phone"`
	Code     string `json:"code"`
	DeviceID string `json:"device_id"`
}

// RequestPhoneChange serves POST /v1/me/phone/request-otp. The OTP is generated by the
// backend and sent through the existing SMS gateway queue, like login.
func (h Me) RequestPhoneChange(w http.ResponseWriter, r *http.Request) {
	var body phoneChangeRequest
	if !decodeBody(w, r, &body) {
		return
	}
	code, err := h.Profiles.RequestPhoneChange(r.Context(), middleware.UserFrom(r.Context()), body.Phone,
		clientIP(r), body.DeviceID, locale(r))
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	resp := map[string]string{"status": "accepted"}
	if h.DevMode && code != "" {
		resp["dev_code"] = code
	}
	httperr.WriteJSON(w, http.StatusAccepted, resp)
}

// ConfirmPhoneChange serves POST /v1/me/phone/verify.
func (h Me) ConfirmPhoneChange(w http.ResponseWriter, r *http.Request) {
	var body phoneChangeRequest
	if !decodeBody(w, r, &body) {
		return
	}
	p, err := h.Profiles.ConfirmPhoneChange(r.Context(), middleware.UserFrom(r.Context()), body.Phone, body.Code)
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	httperr.WriteJSON(w, http.StatusOK, toProfile(p, true))
}

// User serves GET /v1/users/{id}: a public profile without the phone number.
func (h Me) User(w http.ResponseWriter, r *http.Request) {
	p, err := h.Profiles.Public(r.Context(), chi.URLParam(r, "id"))
	if err != nil {
		writeRideErr(w, r, h.Logger, err)
		return
	}
	httperr.WriteJSON(w, http.StatusOK, toProfile(p, false))
}

type vehicleRequest struct {
	Brand          string `json:"brand"`
	Model          string `json:"model"`
	Color          string `json:"color"`
	Plate          string `json:"plate"`
	Year           *int   `json:"year"`
	VehicleType    string `json:"vehicle_type"`
	PassengerSeats *int   `json:"passenger_seats"`
}

func (v vehicleRequest) model() ride.Vehicle {
	return ride.Vehicle{Brand: v.Brand, Model: v.Model, Color: v.Color, Plate: v.Plate, Year: v.Year,
		Type: v.VehicleType, PassengerSeats: v.PassengerSeats}
}

